    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            // Crea el objeto Personal con lo que el usuario escribió en los campos
            Personal p = new Personal(txtTipoDoc.getText(), txtNroDoc.getText(),
                    txtNombre.getText(), txtPaterno.getText(), txtMaterno.getText(),
                    LocalDate.parse(txtFecha.getText()),
                    txtIdPersonal.getText(), txtCargo.getText(),
                    txtEspecialidad.getText(),
                    Double.parseDouble(txtSueldo.getText()));
            // Lo guarda en la lista del controller (valida que el documento no se repita)
            pc.registrarPersona(p);
            lblMensaje.setText("Personal registrado correctamente");
        } catch (DateTimeParseException e) {
            // La fecha no tiene el formato AAAA-MM-DD
            lblMensaje.setText("La fecha debe tener el formato AAAA-MM-DD");
        } catch (NumberFormatException e) {
            // El sueldo no es un número (va antes que IllegalArgumentException
            // porque es una excepción más específica)
            lblMensaje.setText("El sueldo debe ser un numero. Ej: 3500");
        } catch (IllegalArgumentException e) {
            // Error de validación de algún setter o documento repetido
            lblMensaje.setText(e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // Busca por número de documento en la lista de personas
        Persona p = pc.buscarPorDocumento(txtNroDoc.getText().trim());
        if (p == null) {
            // No hay nadie con ese documento: se ocultan los datos
            lblMensaje.setText("No existe ninguna persona con ese documento");
            panelDatos.setVisible(false);
            pack();
            return;
        }
        // La lista guarda Clientes y Personal (herencia): se comprueba que sea Personal
        if (!(p instanceof Personal)) {
            lblMensaje.setText("Ese documento pertenece a un cliente, no a personal");
            panelDatos.setVisible(false);
            pack();
            return;
        }
        // Casting: convierte la Persona encontrada en Personal para usar sus métodos
        Personal x = (Personal) p;
        // Muestra los datos del personal en los campos
        txtTipoDoc.setText(x.getTipo_documento());
        txtNombre.setText(x.getNombre());
        txtPaterno.setText(x.getPaterno());
        txtMaterno.setText(x.getMaterno());
        txtFecha.setText(x.getFecha_nacimiento().toString());
        txtIdPersonal.setText(x.getId_personal());
        txtCargo.setText(x.getCargo());
        txtEspecialidad.setText(x.getEspecialidad());
        txtSueldo.setText(String.valueOf(x.getSueldo()));
        panelDatos.setVisible(true);   // muestra el panel con los datos
        lblMensaje.setText("Personal encontrado");
        pack();
    }//GEN-LAST:event_btnBuscarActionPerformed


